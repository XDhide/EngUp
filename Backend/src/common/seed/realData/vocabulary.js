const TOPICS = [];
const WORDS = [];
const seen = new Set();

Object.entries(RAW).forEach(([name, [description, lines]], topicIndex) => {
  TOPICS.push({ name, description });
  for (const line of lines) {
    const [word, phonetic, meaning, example, difficulty] = line.split('|');
    const key = word.toLowerCase();
    if (seen.has(key)) throw new Error(`Từ trùng trong ngân hàng từ vựng: ${word}`);
    seen.add(key);
    WORDS.push({ topicIndex, word, phonetic, meaning, example_sentence: example, difficulty });
  }
});

module.exports = { TOPICS, WORDS };
